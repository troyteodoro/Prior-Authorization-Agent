def test_ra1_meets_both_claimed_criteria_and_abstains_on_the_rest(patients, policies):
    determination = _determine(patients, policies, RA1)
    assert determination.policy_version_id == TREE_ID
    assert determination.outcome is DeterminationOutcome.INSUFFICIENT_EVIDENCE
    verdicts = {r.criterion_id: r.verdict for r in determination.criterion_results}
    assert verdicts == {
        "a": CriterionVerdict.MET,
        "b": CriterionVerdict.MET,
        "c": CriterionVerdict.INSUFFICIENT_EVIDENCE,
        "d": CriterionVerdict.INSUFFICIENT_EVIDENCE,
        "e": CriterionVerdict.INSUFFICIENT_EVIDENCE,
    }
    reasons = {
        r.criterion_id: r.gap_reason
        for r in determination.criterion_results
        if r.gap_reason is not None
    }
    assert reasons == {
        "c": GapReason.NOT_EVALUATED_BY_THIS_SYSTEM,
        "d": GapReason.NOT_EVALUATED_BY_THIS_SYSTEM,
        "e": GapReason.NOT_EVALUATED_BY_THIS_SYSTEM,
    }, "the overall INSUFFICIENT_EVIDENCE is the unclaimed criteria's alone"


def test_ra3_abstains_on_the_drug_and_never_answers_not_met(patients, policies):
    determination = _determine(patients, policies, RA3)
    by_id = {r.criterion_id: r for r in determination.criterion_results}
    assert by_id["a"].verdict is CriterionVerdict.MET
    assert by_id["b"].verdict is CriterionVerdict.INSUFFICIENT_EVIDENCE
    assert by_id["b"].gap_reason is GapReason.NO_EVIDENCE_RETRIEVED
    assert not by_id["b"].spans, "an abstention cites nothing (Art. IV)"
    assert CriterionVerdict.NOT_MET not in {
        r.verdict for r in determination.criterion_results
    }, (
        "a chart with no prescription has not recorded that the patient is not "
        "taking the drug (D40's asymmetry, D111)"
    )


def test_ra2_is_not_covered_and_cites_the_prescription_that_fired_it(
    patients, policies, population
):
    determination = _determine(patients, policies, RA2)
    assert determination.outcome is DeterminationOutcome.NOT_COVERED
    assert determination.criterion_results == [], (
        "an exclusion answers before the criteria chain (D41)"
    )
    assert determination.exclusion_evidence, "a denial with no citation is Art. III skipped"
    quoted = "".join(
        patients.get_document(span.document_id).text[span.char_start : span.char_end]
        for span in determination.exclusion_evidence
    )
    assert ETANERCEPT_SYRINGE in quoted, (
        "the denial must cite the order that fired it, not some other resource "
        "on the chart"
    )
    assert METHOTREXATE_TABLET not in quoted, (
        "the limitation is about the drug infliximab is combined with; citing "
        "the methotrexate order would be citing the criterion it satisfies"
    )


def test_the_pair_differs_by_exactly_the_declared_prescription(patients, population):
    """RA1 and RA2 are one chart and one chart plus a prescription. Asserted
    over what the store reports, because that is what the criteria read."""
    source = {
        (m.code, m.status, m.authored_on) for m in patients.get_medications(RA1)
    }
    clone = {
        (m.code, m.status, m.authored_on) for m in patients.get_medications(RA2)
    }
    added = clone - source
    assert source - clone == set(), "the clone removes nothing"
    assert {code for code, _, _ in added} == {ETANERCEPT_SYRINGE}
    assert all(status == "active" for _, status, _ in added)


def test_every_rheumatology_determination_spends_no_model_call(patients, policies):
    for patient_id in (RA1, RA2, RA3):
        determination = _determine(patients, policies, patient_id)
        assert determination.model_calls == 0
        assert determination.metrics == []


def test_a_rheumatology_request_on_a_bariatric_chart_abstains(patients, policies):
    """The cross-practice case no row labels and the corpus supplies for free:
    a chart in Palmetto's territory with no rheumatology evidence on it at all.
    Every criterion abstains and none is `NOT_MET` — the system says it cannot
    tell, which is what an absent diagnosis licenses (D40) — and no verdict
    rests on anything the note pass produced.

    This chart carries notes, and that is how D113 found the cost the
    rheumatology rows cannot show: `step_extract` is an unconditional entry in
    `STEPS`, so a tree declaring no note criterion still pays to read every
    note on the chart. It changes no verdict, which is why it is a cost and
    not a defect, and it is `T-107`'s to remove — the row where the tree
    declares its extraction schema.
    """
    bariatric_chart_in_palmetto = "ee9d79ee-ba2e-5915-b6d5-c7e700066d40"
    determination = determine(
        policies,
        J_CODE,
        patient_id=bariatric_chart_in_palmetto,
        patient_store=patients,
        as_of=AS_OF,
        extraction_runner=_recorded_runner(),
        verifier=AcceptAllVerifier(),
    )
    assert determination.policy_version_id == TREE_ID
    assert determination.outcome is DeterminationOutcome.INSUFFICIENT_EVIDENCE
    assert {r.verdict for r in determination.criterion_results} == {
        CriterionVerdict.INSUFFICIENT_EVIDENCE
    }
    assert not any(r.spans for r in determination.criterion_results), (
        "no rheumatology criterion may cite this chart's weight-management "
        "notes: the practice boundary is the tree's, and an extracted event "
        "this tree declares no criterion for must reach no verdict"
    )


