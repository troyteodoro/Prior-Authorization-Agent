def test_the_population_carries_three_rheumatology_charts(population):
    cohort = {
        pid: r for pid, r in population.items() if r.get("cohort") == "rheumatology"
    }
    assert set(cohort) == {RA1, RA2, RA3}, (
        "the rheumatology cohort is the two generated charts and the declared "
        "clone of the first (D113)"
    )


def test_the_generated_pair_differs_on_the_drug_criterions_fact(population):
    """Both carry the diagnosis; one carries the drug. That is the whole
    difference the pair exists to make, and it is what lets criterion (a) hold
    fixed while criterion (b) moves."""
    assert population[RA1]["has_active_ra"] and population[RA3]["has_active_ra"]
    assert population[RA1]["has_active_methotrexate"]
    assert not population[RA3]["has_active_methotrexate"]
    assert population[RA3]["methotrexate_orders"] == 0, (
        "RA3's abstention is about a chart with no such order at all, not one "
        "whose order has ended — a completed order is a different case and "
        "test_infliximab_tree.py pins it"
    )


def test_only_the_declared_clone_carries_the_excluded_drug(population):
    carriers = [
        pid for pid, r in population.items() if r.get("has_active_excluded_biologic")
    ]
    assert carriers == [RA2], (
        "Synthea's rheumatoid arthritis module orders no biologic and no JAK "
        "inhibitor, so the only chart carrying one is the declared clone (D113)"
    )


def test_the_charts_are_in_a_state_the_rheumatology_tree_serves(patients, policies):
    tree = policies.get_tree(TREE_ID)
    for patient_id in (RA1, RA2, RA3):
        state = patients.get_jurisdiction_state(patient_id)
        assert state in tree.jurisdiction.states, (
            f"{patient_id[:12]} is in {state}, which this tree does not serve; "
            "the request would resolve elsewhere or not at all (REQ-55)"
        )


