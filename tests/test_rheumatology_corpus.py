"""T-93 — the second practice's charts, as committed (US-10, D113).

`tests/test_infliximab_tree.py` asks whether the tree loads, resolves and
evaluates; it does that over charts written in the test, so it says nothing
about whether a real one exists. This file asks the other half: do the
**committed bundles** carry what the eval rows say they carry, and does a
determination over them answer what the rows label?

What it pins, in the order the question breaks down:

- **The cohort.** Three charts, two generated by Synthea in Palmetto GBA's
  territory and one a declared clone of the first. The generated pair differs
  on exactly the fact criterion (b) turns on.
- **Membership, not codes.** `select_patients.py` selects on codes read out of
  the Synthea module; this is where those codes are asserted to be what the
  policy plane's value sets admit, in each set's declared system (REQ-59).
  A test that only compared codes to codes would pass with the value sets
  deleted.
- **The verdicts.** Each row's labeled criteria, produced over the real store
  with an extraction runner that raises — the rheumatology tree declares no
  note criterion, so zero model calls is a property of the graph and not of a
  counter (A4's shape).
- **The pair.** `RA2` is `RA1`'s chart plus one prescription, and the denial
  cites that prescription. Both halves are asserted: a denial that cited
  something else would still be a denial, and every other test would agree
  with it.
- **What the adapter cannot see.** `get_medications` does not follow a
  `medicationReference` (D111's stated scope). These charts carry such orders;
  none of them is a drug any rheumatology criterion or exclusion reads. That
  was measured for D113 and is pinned here, because a corpus change that put
  methotrexate behind a reference would move an eval label with every other
  check green.

**What this file cannot catch, and where that claim lives.** No committed
chart carries a *completed* order for a drug in either value set — the two
generated charts have one active methotrexate order and none at all, and the
clone adds an active one — so deleting the `status == "active"` filter from
`_active_members` changes nothing here. It is caught by
`test_infliximab_tree.py`, whose charts are written in the test and can hold
a completed order (D65's shape: the corpus cannot distinguish what it does
not contain). Measured by mutation at T-93's close, not assumed.
"""

from __future__ import annotations

import json
from datetime import date
from pathlib import Path

import pytest

from pa_agent.contracts import CriterionVerdict, DeterminationOutcome, GapReason
from pa_agent.determination import determine
