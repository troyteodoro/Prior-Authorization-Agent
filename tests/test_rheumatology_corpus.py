def test_the_diagnosis_is_admitted_by_the_value_set_in_its_declared_system(
    patients, policies
):
    value_set = policies.get_value_set("rheumatoid_arthritis")
    for patient_id in (RA1, RA3):
        conditions = [
            c
            for c in patients.get_conditions(patient_id)
            if c.clinical_status == "active" and value_set.admits(c.code, c.system)
        ]
        assert [c.code for c in conditions] == [RA_SNOMED]
        assert {c.system for c in conditions} == {SNOMED}, (
            "membership is tested inside the set's declared system (REQ-59)"
        )


def test_the_drug_sets_admit_exactly_what_each_chart_carries(patients, policies):
    methotrexate = policies.get_value_set("methotrexate")
    biologics = policies.get_value_set("biologic_dmards_and_jak_inhibitors")

    def admitted(patient_id, value_set):
        return sorted(
            m.code
            for m in patients.get_medications(patient_id)
            if m.status == "active" and value_set.admits(m.code, m.system)
        )

    assert admitted(RA1, methotrexate) == [METHOTREXATE_TABLET]
    assert admitted(RA1, biologics) == []
    assert admitted(RA3, methotrexate) == []
    assert admitted(RA3, biologics) == []
    assert admitted(RA2, methotrexate) == [METHOTREXATE_TABLET]
    assert admitted(RA2, biologics) == [ETANERCEPT_SYRINGE]


def test_the_charts_carry_medications_in_the_system_the_sets_declare(patients):
    """RxNorm, which is the reason a set of the LCD's own ICD-10 codes would
    have matched nobody (D52, REQ-59, D111)."""
    for patient_id in (RA1, RA2, RA3):
        systems = {
            m.system for m in patients.get_medications(patient_id) if m.system
        }
        assert systems == {RXNORM}, f"{patient_id[:12]}: {systems}"


def test_no_unreadable_order_hides_a_drug_a_criterion_reads(patients, population):
    """`get_medications` reads `medicationCodeableConcept` and does not follow a
    `medicationReference` (D111's stated scope). These charts carry such orders
    — measured for D113, all contraceptives and all completed — and this pins
    that none of them is methotrexate or an excluded biologic. If one ever is,
    RA3's abstention becomes an artifact of the adapter rather than a fact
    about the chart, and nothing else in the suite would notice."""
    for patient_id in (RA1, RA2, RA3):
        bundle = json.loads(
            (
                REPO_ROOT / "data" / "patients" / "bundles" /
                population[patient_id]["filename"]
            ).read_text(encoding="utf-8")
        )
        by_url = {e["fullUrl"]: e["resource"] for e in bundle["entry"] if "fullUrl" in e}
        hidden = []
        for entry in bundle["entry"]:
            resource = entry["resource"]
            if resource.get("resourceType") != "MedicationRequest":
                continue
            reference = (resource.get("medicationReference") or {}).get("reference")
            if not reference:
                continue
            medication = by_url.get(reference, {})
            hidden += [
                c.get("code")
                for c in medication.get("code", {}).get("coding", [])
            ]
        assert not ({METHOTREXATE_TABLET, ETANERCEPT_SYRINGE} & set(hidden)), (
            f"{patient_id[:12]}: a drug a criterion reads sits behind a "
            f"medicationReference the adapter does not follow: {hidden}"
        )


