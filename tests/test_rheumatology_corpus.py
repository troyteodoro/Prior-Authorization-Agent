from pa_agent.stores.policy import LocalPolicyStore

from conftest import AcceptAllVerifier

REPO_ROOT = Path(__file__).resolve().parent.parent
POPULATION = REPO_ROOT / "data" / "patients" / "manifest.json"
CASES = REPO_ROOT / "eval" / "cases.json"

TREE_ID = "infliximab-ra-jjm-v1"
J_CODE = "J1745"
#: The harness clock (D35), which every row without its own `as_of` reads.
AS_OF = date(2026, 9, 1)

SNOMED = "http://snomed.info/sct"
RXNORM = "http://www.nlm.nih.gov/research/umls/rxnorm"
RA_SNOMED = "69896004"
METHOTREXATE_TABLET = "105585"
ETANERCEPT_SYRINGE = "802652"

#: The three charts by the row each one carries. Written here rather than
#: derived, so a chart swapped underneath the eval set fails this file first.
RA1 = "42a430ab-b7ca-87a5-279f-ee115f49fd6e"  # active diagnosis, active drug
RA2 = "915602a8-a36d-59bf-b667-47496ab57965"  # RA1 plus the excluded drug
RA3 = "455d3f7d-3b99-dad6-c0b2-d5405144e793"  # active diagnosis, no drug


class _RaisingRunner:
    """A4: reached only if the graph asks a model something. It must not."""

    name = "raises"

    def run(self, *args, **kwargs):  # pragma: no cover - the point is it is unused
        raise AssertionError(
            "the rheumatology tree declares no note-event criterion; extraction "
            "must never be reached"
        )


@pytest.fixture(scope="module")
def patients() -> LocalPatientStore:
    return LocalPatientStore()


@pytest.fixture(scope="module")
def policies() -> LocalPolicyStore:
    return LocalPolicyStore()


@pytest.fixture(scope="module")
def population() -> dict[str, dict]:
    manifest = json.loads(POPULATION.read_text(encoding="utf-8"))
    return {r["patient_id"]: r for r in manifest["bundles"]}


@pytest.fixture(scope="module")
def cases() -> dict[str, dict]:
    payload = json.loads(CASES.read_text(encoding="utf-8"))
    return {c["case_id"]: c for c in payload["cases"]}


def _determine(patients, policies, patient_id):
    return determine(
        policies,
        J_CODE,
        patient_id=patient_id,
        patient_store=patients,
        as_of=AS_OF,
        extraction_runner=_RaisingRunner(),
        verifier=AcceptAllVerifier(),
    )


def _recorded_runner():
    """T-15's recording, for the one case here whose chart carries notes.
    Spends nothing and replays what was measured (D45)."""
    recording = json.loads(
        (REPO_ROOT / "eval" / "extraction" / "results.json").read_text(encoding="utf-8")
    )
    return RecordedExtractionRunner.from_records(
        recording["notes"], model=recording.get("model")
    )


