def test_every_ultrasound_row_names_a_chart_in_the_cohort(cases, population):
    cohort = {
        r["patient_id"] for r in population["bundles"] if r["cohort"] == "ultrasound"
    }
    rows = [c for c in cases if c["case_id"].startswith("US")]
    assert len(rows) == 4
    for row in rows:
        assert row["patient_id"] in cohort, row["case_id"]


def test_only_the_row_whose_verdict_ages_pins_an_as_of(cases):
    """The `MET` direction is monotone in time and the `NOT_MET` direction is
    not, so exactly one of these rows carries its own clock (D114)."""
    rows = {c["case_id"]: c for c in cases if c["case_id"].startswith("US")}
    assert rows["US2"]["as_of"] == US2_AS_OF.isoformat()
    for case_id in ("US1", "US3", "US4"):
        assert "as_of" not in rows[case_id]
