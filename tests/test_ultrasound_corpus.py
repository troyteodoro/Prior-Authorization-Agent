def test_us1_meets_both_claimed_criteria_and_abstains_on_the_rest(
    patients, policies
):
    determination = _determine(patients, policies, US1)
    assert determination.policy_version_id == TREE_ID
    assert determination.outcome is DeterminationOutcome.INSUFFICIENT_EVIDENCE
    assert _result(determination, "a").verdict is CriterionVerdict.MET
    interval = _result(determination, "b")
    assert interval.verdict is CriterionVerdict.MET
    assert len(interval.spans) == 1
    for criterion_id in ("c", "d", "e"):
        result = _result(determination, criterion_id)
        assert result.verdict is CriterionVerdict.INSUFFICIENT_EVIDENCE
        assert result.gap_reason is GapReason.NOT_EVALUATED_BY_THIS_SYSTEM


def test_us2_is_not_met_and_cites_the_study_inside_the_interval(patients, policies):
    determination = _determine(patients, policies, US2, as_of=US2_AS_OF)
    assert determination.outcome is DeterminationOutcome.NOT_MET
    interval = _result(determination, "b")
    assert interval.verdict is CriterionVerdict.NOT_MET
    assert interval.shortfall.observed == 3
    assert interval.shortfall.required == 12
    assert interval.shortfall.unit == "months_since_prior_procedure"
    assert len(interval.spans) == 1


def test_us2_cites_the_declared_study_and_not_some_other_procedure(
    patients, policies
):
    """A denial that cited the wrong resource would still be a denial, and
    every other check here would agree with it (D113's rule for the
    exclusion, on the criterion this row turns on)."""
    determination = _determine(patients, policies, US2, as_of=US2_AS_OF)
    cited = _result(determination, "b").spans[0]
    declared = next(
        p for p in patients.get_procedures(US2) if p.code == STUDY
    )
    assert cited == declared.span


def test_us3_abstains_on_the_frequency_criterion_and_never_answers_met(
    patients, policies
):
    determination = _determine(patients, policies, BASE)
    assert determination.outcome is DeterminationOutcome.INSUFFICIENT_EVIDENCE
    assert _result(determination, "a").verdict is CriterionVerdict.MET
    interval = _result(determination, "b")
    assert interval.verdict is CriterionVerdict.INSUFFICIENT_EVIDENCE
    assert interval.gap_reason is GapReason.NO_EVIDENCE_RETRIEVED
    assert interval.spans == []


def test_us4_is_no_policy_found_in_a_state_that_is_served(patients, policies):
    result = _determine(patients, policies, BASE, code=UNLISTED_CODE)
    assert type(result).__name__ == "NoPolicyResult"
    assert policies.trees_for_state(WPS_STATE_CODE)


def test_every_cited_span_slices_back_into_the_bundle_it_names(patients, policies):
    """Article III over the structured plane: the span is an extent in the
    bundle's own JSON, and slicing it has to reach the resource the verdict
    says it cites."""
    checked = 0
    for patient_id, as_of in ((US1, AS_OF), (US2, US2_AS_OF), (BASE, AS_OF)):
        determination = _determine(patients, policies, patient_id, as_of=as_of)
        for result in determination.criterion_results:
            for span in result.spans:
                document = patients.get_document(span.document_id)
                sliced = document.text[span.char_start : span.char_end]
                assert json.loads(sliced)["resourceType"] in {
                    "Condition",
                    "Procedure",
                }
                checked += 1
    assert checked >= 9


def test_every_ultrasound_determination_spends_no_model_call(patients, policies):
    for patient_id, as_of in ((US1, AS_OF), (US2, US2_AS_OF), (BASE, AS_OF)):
        determination = _determine(patients, policies, patient_id, as_of=as_of)
        assert not determination.metrics


def test_no_ultrasound_criterion_cites_a_note(patients, policies):
    """These charts are note-free, and the tree declares no note criterion.
    Pinned because `step_extract` is unconditional (D113's finding): a chart
    with notes under this tree would still be read, and the guarantee that
    matters is that nothing it read reaches a verdict. T-107 removes the
    call."""
    note_ids = {d.document_id for d in patients.get_notes(US1)}
    assert note_ids == set()
    determination = _determine(patients, policies, US1)
    cited = {s.document_id for r in determination.criterion_results for s in r.spans}
    assert not cited & note_ids


