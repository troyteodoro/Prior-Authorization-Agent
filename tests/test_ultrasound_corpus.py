def test_the_chart_s_conditions_are_admitted_by_the_indication_set(
    patients, policies
):
    """The value set is the policy plane's claim about what those codes mean;
    the selector only compared codes to codes (Art. VI, REQ-59)."""
    value_set = policies.get_value_set(INDICATIONS)
    admitted = [
        c
        for c in patients.get_conditions(BASE)
        if c.clinical_status == "active" and value_set.admits(c.code, c.system)
    ]
    assert len(admitted) >= 1
    assert {c.system for c in admitted} == {value_set.system}


def test_the_declared_study_is_admitted_by_the_study_set(patients, policies):
    value_set = policies.get_value_set(STUDIES)
    for patient_id in (US1, US2):
        admitted = [
            p
            for p in patients.get_procedures(patient_id)
            if value_set.admits(p.code, p.system)
        ]
        assert len(admitted) == 1
        assert admitted[0].code == STUDY
        assert admitted[0].system == value_set.system
    assert not [
        p
        for p in patients.get_procedures(BASE)
        if value_set.admits(p.code, p.system)
    ]


def test_the_declared_studies_sit_outside_the_excluded_care_settings(patients):
    """The carve-out is the predicate's, and this is the fact that makes it
    inert over this corpus — which is why the behaviour itself is pinned in
    `test_ultrasound_tree.py` and recorded in D114 rather than assumed."""
    for patient_id in (US1, US2):
        declared = [p for p in patients.get_procedures(patient_id) if p.code == STUDY]
        assert [p.encounter_class for p in declared] == ["AMB"]
        assert [p.status for p in declared] == ["completed"]


def test_every_procedure_on_these_charts_resolves_its_care_setting(patients):
    """`Procedure.encounter_class` is `None` when the adapter cannot resolve
    the encounter, and an unresolved setting counts rather than being
    excluded. Measured here so a bundle that started carrying dangling
    encounter references would fail loudly instead of quietly widening what
    the frequency criterion counts (D114)."""
    for patient_id in (BASE, US1, US2):
        unresolved = [
            p for p in patients.get_procedures(patient_id) if p.encounter_class is None
        ]
        assert not unresolved, f"{patient_id}: {len(unresolved)} unresolved setting(s)"


