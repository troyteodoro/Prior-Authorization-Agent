"""T-94 — the third practice's charts, as committed (US-10, D114).

`tests/test_ultrasound_tree.py` asks whether the tree loads, resolves and
evaluates, over charts written in that file. This file asks the other half,
in `test_rheumatology_corpus.py`'s shape: do the **committed bundles** carry
what the eval rows say they carry, and does a determination over them answer
what the rows label?

What it pins:

- **The cohort.** Three charts: one generated by Synthea in WPS's territory
  and two declared clones of it, each carrying one prior study copied from a
  procedure the patient already had and re-coded. The pair differs by exactly
  the date that decides the frequency criterion.
- **Membership, not codes.** `select_patients.py` selects on codes read out of
  the Synthea modules; this is where those codes are asserted to be what the
  policy plane's value sets admit, in each set's declared system (REQ-59). A
  test comparing codes to codes would pass with the value sets deleted.
- **The verdicts.** Each row's labeled criteria over the real store, with an
  extraction runner that raises: this tree declares no note criterion, so zero
  model calls is a property of the graph and not of a counter.
- **The spans.** Every cited span slices back into the bundle it names, which
  is the whole of Article III on the structured plane.

**What this file cannot catch, and where that claim lives.** No committed
chart carries an abdominal vascular study at an emergency or inpatient
encounter, or one the record disowns — the declared studies are copies of
ambulatory, completed procedures — so a predicate that ignored L35755's
care-setting carve-out, or counted a `not-done` study, would pass everything
here. Both are caught by `test_ultrasound_tree.py` on charts written in the
test (D65's division, D113's tenth mutation seen coming).
"""

from __future__ import annotations

import json
from datetime import date
from pathlib import Path

import pytest

from pa_agent.contracts import CriterionVerdict, DeterminationOutcome, GapReason
from pa_agent.determination import determine
from pa_agent.stores.patient import LocalPatientStore
from pa_agent.stores.policy import LocalPolicyStore

from conftest import AcceptAllVerifier

REPO_ROOT = Path(__file__).resolve().parent.parent
POPULATION = REPO_ROOT / "data" / "patients" / "manifest.json"
BUNDLES = REPO_ROOT / "data" / "patients" / "bundles"
CASES = REPO_ROOT / "eval" / "cases.json"

TREE_ID = "us-abdominal-visceral-j5-j8-v1"
US_CODE = "93975"
UNLISTED_CODE = "76700"
WPS_STATE_CODE = "IA"

SNOMED = "http://snomed.info/sct"
STUDY = "709640007"
INDICATIONS = "abdominal_visceral_vascular_indications"
STUDIES = "abdominal_visceral_vascular_studies"

#: The three charts by the row each one carries. Written here rather than
#: derived, so a chart swapped underneath the eval set fails this file first.
BASE = "53126ee7-0f8a-b494-fb3c-921069a1605b"  # the generated chart, no study
US1 = "b1bbb34a-aa4b-5c18-a550-8bd26e0da528"  # one study, outside the interval
US2 = "7acd0453-b37c-5c1a-9879-0a7b443065d9"  # one study, inside it

#: `US2` pins its own `as_of` because the `NOT_MET` direction ages out; the
#: other two do not need one and are read at the harness clock (D114).
US2_AS_OF = date(2026, 9, 1)
AS_OF = date(2026, 9, 1)


class _RaisingRunner:
    name = "raising"

    def run(self, *args, **kwargs):  # pragma: no cover - the point is the raise
        raise AssertionError("the ultrasound tree declares no note criterion")


@pytest.fixture(scope="module")
def population() -> dict:
    return json.loads(POPULATION.read_text(encoding="utf-8"))


@pytest.fixture(scope="module")
def patients() -> LocalPatientStore:
    return LocalPatientStore()


@pytest.fixture(scope="module")
def policies() -> LocalPolicyStore:
    return LocalPolicyStore()


@pytest.fixture(scope="module")
def cases() -> list[dict]:
    return json.loads(CASES.read_text(encoding="utf-8"))["cases"]


def _determine(patients, policies, patient_id, code=US_CODE, as_of=AS_OF):
    return determine(
        policies,
        code,
        patient_id=patient_id,
        patient_store=patients,
        as_of=as_of,
        extraction_runner=_RaisingRunner(),
        verifier=AcceptAllVerifier(),
    )


def _result(determination, criterion_id: str):
    return next(
        r for r in determination.criterion_results if r.criterion_id == criterion_id
    )


def _record(population: dict, patient_id: str) -> dict:
    return next(r for r in population["bundles"] if r["patient_id"] == patient_id)


