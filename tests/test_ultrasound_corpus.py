def test_the_population_carries_three_ultrasound_charts(population):
    cohort = [r for r in population["bundles"] if r["cohort"] == "ultrasound"]
    assert sorted(r["patient_id"] for r in cohort) == sorted([BASE, US1, US2])


def test_the_generated_chart_carries_the_indication_and_no_study_of_its_own(
    population,
):
    record = _record(population, BASE)
    assert record["active_indication_codes"], "criterion (a)'s fact"
    assert record["prior_study_dates"] == [], (
        "the generated chart carries no abdominal vascular study, so each "
        "clone's declared study is the only one on its chart"
    )


def test_each_clone_carries_exactly_one_declared_study_and_the_dates_differ(
    population,
):
    outside = _record(population, US1)["prior_study_dates"]
    inside = _record(population, US2)["prior_study_dates"]
    assert len(outside) == len(inside) == 1
    assert outside[0][:10] == "2024-06-17"
    assert inside[0][:10] == "2026-05-25"


def test_the_pair_differs_by_exactly_the_declared_procedure(population):
    """`US1` and `US2` are the same chart with a different procedure copied
    and re-coded. Asserted on the bytes, because the whole legibility of the
    two rows is that one field moved (D113's shape for the prescription)."""
    entries = {}
    for patient_id in (US1, US2):
        bundle = json.loads(
            (BUNDLES / _record(population, patient_id)["filename"]).read_text(
                encoding="utf-8"
            )
        )
        entries[patient_id] = [
            e
            for e in bundle["entry"]
            if e["resource"]["resourceType"] == "Procedure"
            and STUDY in {c["code"] for c in e["resource"]["code"]["coding"]}
        ]
    for patient_id, declared in entries.items():
        assert len(declared) == 1, f"{patient_id} carries {len(declared)} declared study"
        assert declared[0]["resource"]["id"].endswith("-us-prior-synthetic")
    assert entries[US1][0]["resource"]["encounter"] != (
        entries[US2][0]["resource"]["encounter"]
    ), "the two studies were copied from procedures at different encounters"


def test_the_charts_are_in_a_state_the_ultrasound_tree_serves(patients, policies):
    for patient_id in (BASE, US1, US2):
        state = patients.get_jurisdiction_state(patient_id)
        assert state == WPS_STATE_CODE
        assert policies.resolve(US_CODE, state).policy_version_id == TREE_ID


